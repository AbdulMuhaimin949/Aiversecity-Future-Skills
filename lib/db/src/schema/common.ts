import { pgEnum, timestamp } from "drizzle-orm/pg-core";

/**
 * Shared column helpers and enums used across the Aiversecity schema.
 *
 * Language codes follow BCP 47: Bahasa Melayu (`ms`, the default),
 * Simplified Chinese (`zh-CN`) and English (`en`).
 */
export const SUPPORTED_LANGUAGES = ["ms", "zh-CN", "en"] as const;
export type LanguageCode = (typeof SUPPORTED_LANGUAGES)[number];
export const DEFAULT_LANGUAGE: LanguageCode = "ms";

/**
 * Where a catalogue record came from.
 * - SOURCE_ATTRIBUTED: the pipeline marks it non-synthetic and cites a public
 *   source (MASCO, ESCO, ...). It does not mean every field was independently
 *   checked against that source.
 * - SYNTHETIC: generated by the project's synthetic data generator.
 */
export const dataOriginEnum = pgEnum("data_origin", [
  "SOURCE_ATTRIBUTED",
  "SYNTHETIC",
]);

export const createdAt = () =>
  timestamp("created_at", { withTimezone: true }).notNull().defaultNow();

export const updatedAt = () =>
  timestamp("updated_at", { withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date());
